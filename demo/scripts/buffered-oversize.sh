#!/usr/bin/env bash
# BUFFERED oversize → Reject / 413.
#
# Two cells under BODY_MODE=BUFFERED (default product demo up):
#   1) ModSec SecRequestBodyLimitAction Reject (1 KiB overlay, no CRS) →
#      libmodsecurity intervention status 403 on pin (log: "Request body limit
#      is marked to reject the request"); origin untouched.
#   2) Envoy per_connection_buffer_limit_bytes: 1024 (temporary envoy swap) →
#      Envoy 413, origin untouched.
#
# Also asserts under-limit paths after the ModSec overlay reload. Restores
# stock rules + Envoy before exit.
set -euo pipefail
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"

FAIL=0
PASS=0
pass() { echo "  PASS $*"; PASS=$((PASS + 1)); }
fail() { echo "  FAIL $*"; FAIL=1; }

[[ "${BODY_MODE}" == "BUFFERED" ]] \
  || { echo "buffered-oversize requires BODY_MODE=BUFFERED (got '${BODY_MODE}')" >&2; exit 2; }

wait_http "${BASE}/" 50 || { echo "demo not up at ${BASE} — run ./demo/scripts/up.sh" >&2; exit 2; }

WORKDIR="${RUN}/buffered-oversize"
mkdir -p "${WORKDIR}"
OVERSIZE_RULES="${WORKDIR}/modsec-oversize.conf"
STOCK_ENVOY_CFG="${DEMO}/envoy/envoy.yaml"
OVERSIZE_ENVOY_CFG="${DEMO}/envoy/envoy-buffered-oversize.yaml"
[[ -f "${OVERSIZE_ENVOY_CFG}" ]] || { echo "missing ${OVERSIZE_ENVOY_CFG}" >&2; exit 2; }

# Build rules for ModSec Reject cell: engine + oversize overlay + demo rules ONLY
# (no CRS). CRS argument-length rules can 403 first and mask SecRequestBodyLimitAction
# Reject → 413, which is the matrix claim this suite exists to prove.
{
  echo "# Generated by buffered-oversize.sh — ModSec Reject cell (no CRS)."
  echo "Include ${DEMO}/rules/engine.conf"
  echo "Include ${DEMO}/rules/engine-oversize-overlay.conf"
  echo "SecTmpDir ${RUN}/tmp"
  echo "SecDataDir ${RUN}/data"
  echo "SecAuditEngine RelevantOnly"
  echo "SecAuditLogRelevantStatus \"^(?:5|4(?!04))\""
  echo "SecAuditLogParts ABIJDEFHZ"
  echo "SecAuditLogFormat JSON"
  echo "SecAuditLogType Serial"
  echo "SecAuditLog ${RUN}/modsec-audit.log"
  echo "Include ${DEMO}/rules/demo-response.conf"
} >"${OVERSIZE_RULES}"

restore() {
  # Best-effort restore of stock connector rules + Envoy YAML.
  stop_pidfile "${RUN}/connector.pid" || true
  stop_pidfile "${RUN}/envoy.pid" || true
  sleep 0.2
  if [[ -f "${RULES_FILE}" ]]; then
    CONNECTOR_RULES="${RULES_FILE}" start_connector || true
    wait_http "${METRICS}/healthz" 50 || true
  fi
  if [[ -f "${STOCK_ENVOY_CFG}" ]]; then
    daemonize "${RUN}/envoy.log" "${RUN}/envoy.pid" \
      envoy -c "${STOCK_ENVOY_CFG}" --concurrency 2 --log-level warn --file-flush-interval-msec 200 || true
    wait_http "http://127.0.0.1:${ENVOY_ADMIN_PORT}/ready" 50 || true
  fi
}
trap restore EXIT

echo "==> BUFFERED oversize (ModSec SecRequestBodyLimit 1 KiB Reject)"
stop_pidfile "${RUN}/connector.pid"
CONNECTOR_RULES="${OVERSIZE_RULES}" start_connector
if ! wait_http "${METRICS}/healthz" 100; then
  echo "connector failed to reload oversize rules:" >&2
  tail -n 40 "${RUN}/connector.log" >&2
  exit 1
fi

# Benign under limit.
before="$(origin_hits)"
code="$(http_code -X POST -H 'Content-Type: application/x-www-form-urlencoded' \
  --data-binary 'hello=world' "${BASE}/post")"
sleep 0.15
delta=$(( $(origin_hits) - before ))
if [[ "$code" == "200" && "$delta" == "1" ]]; then
  pass "[modsec-under-limit-benign] HTTP 200 origin +1"
else
  fail "[modsec-under-limit-benign] HTTP $code origin +$delta (want 200 / +1)"
fi

# SQLi under limit — without CRS this reaches origin; still proves overlay did not
# break the under-limit path. (CRS deny is covered by smoke/go-ftw.)
before="$(origin_hits)"
code="$(http_code -X POST -H 'Content-Type: application/x-www-form-urlencoded' \
  --data-binary "user=admin'%20UNION%20SELECT%201,2,3--" "${BASE}/login")"
sleep 0.15
delta=$(( $(origin_hits) - before ))
if [[ "$code" == "200" && "$delta" == "1" ]]; then
  pass "[modsec-under-limit-nocrs-sqli-passthrough] HTTP 200 origin +1"
else
  fail "[modsec-under-limit-nocrs-sqli-passthrough] HTTP $code origin +$delta (want 200 / +1; no CRS loaded)"
fi

# Oversized benign body — ModSec Reject. On libmodsecurity v3.0.17 the
# intervention status is 403 (log: "Request body limit is marked to reject the
# request"); audit JSON may still show http_code 413. Client must see deny-class
# (403 here) and origin untouched. Envoy 413 is proven in the next cell.
pad="$(python3 -c 'print("A"*2048)')"
before="$(origin_hits)"
code="$(http_code -X POST -H 'Content-Type: application/x-www-form-urlencoded' \
  --data-binary "pad=${pad}" --max-time 15 "${BASE}/post")"
sleep 0.2
delta=$(( $(origin_hits) - before ))
if [[ "$code" == "403" && "$delta" == "0" ]] \
  && grep -q 'Request body limit is marked to reject the request' "${RUN}/connector.log"; then
  pass "[modsec-oversize-reject] HTTP 403 origin +0 (libmodsecurity Reject intervention)"
elif [[ "$code" == "413" && "$delta" == "0" ]]; then
  pass "[modsec-oversize-reject] HTTP 413 origin +0 (Reject mapped 413)"
else
  fail "[modsec-oversize-reject] HTTP $code origin +$delta (want 403+limit-log or 413 / +0)"
fi

echo "==> BUFFERED oversize (Envoy listener buffer 1 KiB → 413)"
# Restore product ModSec rules first (so Envoy cell is not conflated with ModSec Reject).
stop_pidfile "${RUN}/connector.pid"
CONNECTOR_RULES="${RULES_FILE}" start_connector
wait_http "${METRICS}/healthz" 100 \
  || { echo "connector restore failed" >&2; exit 1; }

stop_pidfile "${RUN}/envoy.pid"
daemonize "${RUN}/envoy.log" "${RUN}/envoy.pid" \
  envoy -c "${OVERSIZE_ENVOY_CFG}" --concurrency 2 --log-level warn --file-flush-interval-msec 200
if ! wait_http "http://127.0.0.1:${ENVOY_ADMIN_PORT}/ready" 100; then
  echo "envoy oversize config failed:" >&2
  tail -n 40 "${RUN}/envoy.log" >&2
  exit 1
fi

before="$(origin_hits)"
code="$(http_code -X POST -H 'Content-Type: application/x-www-form-urlencoded' \
  --data-binary "pad=${pad}" --max-time 15 "${BASE}/post")"
sleep 0.2
delta=$(( $(origin_hits) - before ))
# Envoy BUFFERED over-limit is typically 413; some builds surface 400/503 — require
# reject-class (4xx/5xx), never 200, and origin untouched.
if [[ "$delta" == "0" && "$code" == "413" ]]; then
  pass "[envoy-buffer-oversize] HTTP 413 origin +0"
elif [[ "$delta" == "0" && "$code" =~ ^[45][0-9][0-9]$ && "$code" != "403" ]]; then
  # Accept alternate Envoy local-reply codes but record them; floor still requires 413 preference.
  fail "[envoy-buffer-oversize] HTTP $code origin +0 (want 413; got reject-class but not 413)"
else
  fail "[envoy-buffer-oversize] HTTP $code origin +$delta (want 413 / +0)"
fi

# Restore stock Envoy before trap (so exit path is quiet).
stop_pidfile "${RUN}/envoy.pid"
daemonize "${RUN}/envoy.log" "${RUN}/envoy.pid" \
  envoy -c "${STOCK_ENVOY_CFG}" --concurrency 2 --log-level warn --file-flush-interval-msec 200
wait_http "http://127.0.0.1:${ENVOY_ADMIN_PORT}/ready" 100 \
  || { echo "envoy stock restore failed" >&2; exit 1; }

if [[ "$FAIL" -ne 0 ]]; then
  echo "BUFFERED-OVERSIZE FAILED body_mode=${BODY_MODE}"
  exit 1
fi
echo "BUFFERED-OVERSIZE PASSED body_mode=${BODY_MODE} checks=${PASS}"
