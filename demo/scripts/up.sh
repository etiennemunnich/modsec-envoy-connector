#!/usr/bin/env bash
# Start the local demo: origin :18098, connector :18081 (metrics :18082),
# Envoy :18080 (admin :18089). Loads engine.conf + CRS + connex-demo.conf.
#
#   DEMO_CRS=0 ./demo/scripts/up.sh   # skip CRS (demo rules only)
set -euo pipefail
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"

command -v envoy >/dev/null || { echo "envoy not on PATH — run demo/scripts/install-envoy.sh" >&2; exit 2; }
pkg-config --exists modsecurity 2>/dev/null || { echo "libmodsecurity not found — run demo/scripts/install-libmodsecurity.sh" >&2; exit 2; }

"${DEMO}/scripts/down.sh" >/dev/null 2>&1 || true
ports_free_or_die
mkdir -p "${RUN}/tmp" "${RUN}/data"
: >"${HITS_FILE}"
: >"${RUN}/connector.log"
: >"${RUN}/envoy.log"

{
  echo "# Generated by demo/scripts/up.sh — do not edit."
  echo "Include ${DEMO}/rules/engine.conf"
  echo "SecTmpDir ${RUN}/tmp"
  echo "SecDataDir ${RUN}/data"
  echo "SecAuditEngine RelevantOnly"
  echo "SecAuditLogRelevantStatus \"^(?:5|4(?!04))\""
  echo "SecAuditLogParts ABIJDEFHZ"
  echo "SecAuditLogFormat JSON"
  echo "SecAuditLogType Serial"
  echo "SecAuditLog ${RUN}/modsec-audit.log"
  if [[ "${DEMO_CRS:-1}" == "1" ]]; then
    [[ -d "${CRS_DIR}/rules" ]] || "${DEMO}/scripts/install-crs.sh" >&2
    echo "Include ${CRS_DIR}/crs-setup.conf"
    echo "Include ${CRS_DIR}/rules/*.conf"
  fi
  echo "Include ${DEMO}/rules/connex-demo.conf"
} >"${RULES_FILE}"

echo "==> cargo build -p ext-proc-modsec"
(cd "${ROOT}" && cargo build -q -p ext-proc-modsec)

echo "==> origin :${ORIGIN_PORT}"
daemonize "${RUN}/origin.log" "${RUN}/origin.pid" python3 "${DEMO}/scripts/origin.py" "${ORIGIN_PORT}" "${HITS_FILE}"

echo "==> connector ${CONNECTOR_LISTEN} (rules: ${RULES_FILE})"
start_connector
if ! wait_http "${METRICS}/healthz" 100; then
  echo "connector failed to become ready:" >&2
  tail -n 40 "${RUN}/connector.log" >&2
  exit 1
fi

echo "==> envoy :18080 ($(envoy --version 2>&1 | grep -o '1\.[0-9]*\.[0-9]*' | head -1))"
daemonize "${RUN}/envoy.log" "${RUN}/envoy.pid" envoy -c "${ENVOY_CFG}" --concurrency 2 --log-level warn --file-flush-interval-msec 200
if ! wait_http "http://127.0.0.1:${ENVOY_ADMIN_PORT}/ready" 100; then
  echo "envoy failed to become ready:" >&2
  tail -n 40 "${RUN}/envoy.log" >&2
  exit 1
fi

cat <<EOF

Demo up.
  App (through Envoy + ModSecurity): ${BASE}/
  Connector metrics / readiness:     ${METRICS}/metrics  ${METRICS}/healthz
  Logs:                              ${RUN}/{envoy,connector,origin}.log
  ModSecurity audit log:             ${RUN}/modsec-audit.log
Next: ./demo/scripts/smoke.sh   ./demo/scripts/fail-closed.sh   ./demo/scripts/down.sh
EOF
