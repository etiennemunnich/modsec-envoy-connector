#!/usr/bin/env bash
# Start the local demo: origin :18098, connector :18081 (metrics :18082),
# Envoy :18080 (admin :18089). Loads engine.conf + CRS + demo-response.conf.
#
#   ./demo/scripts/up.sh                       # BUFFERED (default)
#   BODY_MODE=STREAMED ./demo/scripts/up.sh    # see demo/scripts/lib.sh for modes
#   DEMO_CRS=0 ./demo/scripts/up.sh            # skip CRS (demo rules only)
#   DEMO_PORT_BASE=18380 ./demo/scripts/up.sh  # every port moves by the same offset
set -euo pipefail
# A previous run's saved body mode applies to the suites, not to a fresh start.
BODY_MODE="${BODY_MODE:-BUFFERED}"
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"

command -v envoy >/dev/null || { echo "envoy not on PATH — run demo/scripts/install-envoy.sh (Linux: put ~/.local/bin first on PATH)" >&2; exit 2; }
pkg-config --exists modsecurity 2>/dev/null || { echo "libmodsecurity not found by pkg-config (PKG_CONFIG_PATH=${PKG_CONFIG_PATH:-}) — run demo/scripts/install-libmodsecurity.sh" >&2; exit 2; }

"${DEMO}/scripts/down.sh" >/dev/null 2>&1 || true
ports_free_or_die
mkdir -p "${RUN}/tmp" "${RUN}/data"
echo "${BODY_MODE}" >"${RUN}/body_mode"
: >"${HITS_FILE}"
: >"${RUN}/connector.log"
: >"${RUN}/envoy.log"

{
  echo "# Generated by demo/scripts/up.sh — do not edit."
  echo "Include ${DEMO}/rules/engine.conf"
  if [[ "${BODY_MODE}" == "BUFFERED_PARTIAL" ]]; then
    echo "Include ${DEMO}/rules/engine-partial-overlay.conf"
  fi
  echo "SecTmpDir ${RUN}/tmp"
  echo "SecDataDir ${RUN}/data"
  echo "SecAuditEngine RelevantOnly"
  echo "SecAuditLogRelevantStatus \"^(?:5|4(?!04))\""
  echo "SecAuditLogParts ABIJDEFHZ"
  echo "SecAuditLogFormat JSON"
  echo "SecAuditLogType Serial"
  echo "SecAuditLog ${RUN}/modsec-audit.log"
  if [[ "${DEMO_CRS:-1}" == "1" ]]; then
    [[ -d "${CRS_DIR}/rules" ]] || "${DEMO}/scripts/install-crs.sh" >&2
    echo "Include ${CRS_DIR}/crs-setup.conf"
    echo "Include ${CRS_DIR}/rules/*.conf"
  fi
  echo "Include ${DEMO}/rules/demo-response.conf"
} >"${RULES_FILE}"

echo "==> cargo build -p ext-proc-modsec"
(cd "${ROOT}" && cargo build -q -p ext-proc-modsec)

echo "==> origin :${ORIGIN_PORT}"
daemonize "${RUN}/origin.log" "${RUN}/origin.pid" python3 "${DEMO}/scripts/origin.py" "${ORIGIN_PORT}" "${HITS_FILE}"

echo "==> connector ${CONNECTOR_LISTEN} body_reply=${BODY_REPLY} (rules: ${RULES_FILE})"
start_connector
if ! wait_http "${METRICS}/healthz" 100; then
  echo "connector failed to become ready:" >&2
  tail -n 40 "${RUN}/connector.log" >&2
  exit 1
fi

grep -q "request_body_mode: ${REQUEST_BODY_MODE}" "${ENVOY_CFG}" \
  || { echo "${ENVOY_CFG} must set request_body_mode: ${REQUEST_BODY_MODE}" >&2; exit 2; }
grep -q "response_body_mode: ${RESPONSE_BODY_MODE}" "${ENVOY_CFG}" \
  || { echo "${ENVOY_CFG} must set response_body_mode: ${RESPONSE_BODY_MODE}" >&2; exit 2; }
if [[ "${BODY_MODE}" == "FULL_DUPLEX_STREAMED" ]]; then
  grep -q 'request_trailer_mode: SEND' "${ENVOY_CFG}" \
    || { echo "${ENVOY_CFG} must set request_trailer_mode: SEND for FULL_DUPLEX_STREAMED" >&2; exit 2; }
  [[ "${BODY_REPLY}" == "streamed" ]] \
    || { echo "FULL_DUPLEX_STREAMED requires BODY_REPLY=streamed" >&2; exit 2; }
fi

echo "==> envoy :${ENVOY_PORT} ($(envoy --version 2>&1 | grep -o '1\.[0-9]*\.[0-9]*' | head -1)) body_mode=${BODY_MODE} (req=${REQUEST_BODY_MODE} resp=${RESPONSE_BODY_MODE})"
daemonize "${RUN}/envoy.log" "${RUN}/envoy.pid" envoy -c "${ENVOY_CFG}" --concurrency 2 --log-level warn --file-flush-interval-msec 200
if ! wait_http "http://127.0.0.1:${ENVOY_ADMIN_PORT}/ready" 100; then
  echo "envoy failed to become ready:" >&2
  tail -n 40 "${RUN}/envoy.log" >&2
  exit 1
fi

cat <<EOF

Demo up (body_mode=${BODY_MODE}).
  App (through Envoy + ModSecurity): ${BASE}/
  Connector metrics / readiness:     ${METRICS}/metrics  ${METRICS}/healthz
  Envoy config:                      ${ENVOY_CFG}
  Logs:                              ${RUN}/{envoy,connector,origin}.log
  ModSecurity audit log:             ${RUN}/modsec-audit.log
Next: ./demo/scripts/smoke.sh   ./demo/scripts/fail-closed.sh   ./demo/scripts/down.sh
EOF
