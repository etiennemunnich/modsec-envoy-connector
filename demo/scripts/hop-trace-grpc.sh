#!/usr/bin/env bash
# Live gRPC hop-trace through Envoy → connector → grpc-echo origin.
#
# Honest bound:
#   - Inspected: request headers / :path / gRPC metadata (HTTP/2 headers).
#   - NOT claimed: full protobuf CRS, streaming RPC WAF, or "gRPC body CRS".
#   - Envoy config: demo/envoy/envoy-grpc.yaml (HTTP/2, body modes NONE).
#   - Allow/deny cells use DEMO_CRS=0 + connex-grpc-demo.conf so benign Unary
#     can Continue; a separate cell reloads stock CRS to show path anomaly deny.
#
# Floors (empty suite cannot go green):
#   MIN_GRPC_CHECKS (default 6) proven cells must PASS.
#
# Usage:
#   ./demo/scripts/up.sh && ./demo/scripts/hop-trace-grpc.sh
#   Requires: go, grpcurl, envoy, running HTTP demo (reconfigured in-place).
set -euo pipefail
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"

FAIL=0
PASS=0
MIN_GRPC_CHECKS="${MIN_GRPC_CHECKS:-6}"
GRPC_ORIGIN_PORT=18090
GRPC_HITS="${RUN}/grpc-origin-hits.log"
GRPC_CFG="${DEMO}/envoy/envoy-grpc.yaml"
GRPC_RULES_DEMO="${DEMO}/rules/connex-grpc-demo.conf"
GRPC_ECHO_DIR="${DEMO}/grpc-echo"
OUT_DIR="${RUN}/hop-trace-grpc"
mkdir -p "${OUT_DIR}"
TRANSCRIPT="${OUT_DIR}/$(date -u +%Y%m%dT%H%M%SZ).txt"
exec > >(tee "${TRANSCRIPT}") 2>&1

pass() { echo "  PASS $*"; PASS=$((PASS + 1)); }
fail() { echo "  FAIL $*"; FAIL=1; }

command -v grpcurl >/dev/null || { echo "grpcurl not on PATH" >&2; exit 2; }
command -v go >/dev/null || { echo "go not on PATH (needed to build demo/grpc-echo)" >&2; exit 2; }
command -v envoy >/dev/null || { echo "envoy not on PATH" >&2; exit 2; }
[[ -f "${GRPC_CFG}" ]] || { echo "missing ${GRPC_CFG}" >&2; exit 2; }
[[ -f "${GRPC_RULES_DEMO}" ]] || { echo "missing ${GRPC_RULES_DEMO}" >&2; exit 2; }
grep -q 'failure_mode_allow: false' "${GRPC_CFG}" \
  || { echo "${GRPC_CFG} must keep failure_mode_allow: false" >&2; exit 2; }
grep -q 'request_body_mode: NONE' "${GRPC_CFG}" \
  || { echo "${GRPC_CFG} must set request_body_mode: NONE (headers-only)" >&2; exit 2; }
grep -q 'response_body_mode: NONE' "${GRPC_CFG}" \
  || { echo "${GRPC_CFG} must set response_body_mode: NONE" >&2; exit 2; }

wait_http "http://127.0.0.1:${ENVOY_ADMIN_PORT}/ready" 25 \
  || { echo "Envoy not ready — run ./demo/scripts/up.sh first" >&2; exit 2; }

grpc_hits() {
  if [[ -f "${GRPC_HITS}" ]]; then wc -l <"${GRPC_HITS}" | tr -d ' '; else echo 0; fi
}

# grpc_call <rid> [grpcurl -H args...] → prints "rc=<n> grpc-status=<s|?> http=<code|?>"
# Uses echo.proto; records verbose stderr for hop joins.
grpc_call() {
  local rid="$1"
  shift
  local out="${OUT_DIR}/${rid}.out" err="${OUT_DIR}/${rid}.err" rc=0
  set +e
  grpcurl -plaintext \
    -import-path "${GRPC_ECHO_DIR}" -proto echo.proto \
    -H "x-request-id: ${rid}" \
    "$@" \
    -d '{"text":"hop-trace"}' \
    "127.0.0.1:18080" echo.Echo/Unary \
    >"${out}" 2>"${err}"
  rc=$?
  set -e
  local gstat httpc
  gstat="$(grep -i 'grpc-status:' "${err}" | tail -1 | awk '{print $2}' | tr -d '\r' || true)"
  httpc="$(grep -iE '^< HTTP/|HTTP/2 ' "${err}" | tail -1 | awk '{print $2}' | tr -d '\r' || true)"
  echo "rc=${rc} grpc-status=${gstat:-?} http=${httpc:-?}"
}

build_grpc_rules_no_crs() {
  {
    echo "# Generated by hop-trace-grpc.sh — do not edit."
    echo "Include ${DEMO}/rules/engine.conf"
    echo "SecTmpDir ${RUN}/tmp"
    echo "SecDataDir ${RUN}/data"
    echo "SecAuditEngine RelevantOnly"
    echo "SecAuditLogRelevantStatus \"^(?:5|4(?!04))\""
    echo "SecAuditLogParts ABIJDEFHZ"
    echo "SecAuditLogFormat JSON"
    echo "SecAuditLogType Serial"
    echo "SecAuditLog ${RUN}/modsec-audit.log"
    echo "Include ${GRPC_RULES_DEMO}"
  } >"${RUN}/modsec-grpc.conf"
}

restore_stock() {
  stop_pidfile "${RUN}/grpc-echo.pid" TERM
  stop_pidfile "${RUN}/connector.pid" KILL
  stop_pidfile "${RUN}/envoy.pid" TERM
  # Rebuild stock rules (CRS + demo) the same way up.sh does.
  {
    echo "# Generated by hop-trace-grpc.sh restore — do not edit."
    echo "Include ${DEMO}/rules/engine.conf"
    echo "SecTmpDir ${RUN}/tmp"
    echo "SecDataDir ${RUN}/data"
    echo "SecAuditEngine RelevantOnly"
    echo "SecAuditLogRelevantStatus \"^(?:5|4(?!04))\""
    echo "SecAuditLogParts ABIJDEFHZ"
    echo "SecAuditLogFormat JSON"
    echo "SecAuditLogType Serial"
    echo "SecAuditLog ${RUN}/modsec-audit.log"
    if [[ "${DEMO_CRS:-1}" == "1" ]]; then
      [[ -d "${CRS_DIR}/rules" ]] || "${DEMO}/scripts/install-crs.sh" >&2
      echo "Include ${CRS_DIR}/crs-setup.conf"
      echo "Include ${CRS_DIR}/rules/*.conf"
    fi
    echo "Include ${DEMO}/rules/connex-demo.conf"
  } >"${RULES_FILE}"
  CONNECTOR_RULES="" start_connector
  wait_http "${METRICS}/healthz" 100 \
    || { echo "failed to restore connector" >&2; return 1; }
  daemonize "${RUN}/envoy.log" "${RUN}/envoy.pid" \
    envoy -c "${ENVOY_CFG}" --concurrency 2 --log-level warn --file-flush-interval-msec 200
  wait_http "http://127.0.0.1:${ENVOY_ADMIN_PORT}/ready" 100 \
    || { echo "failed to restore Envoy ${ENVOY_CFG}" >&2; return 1; }
  wait_http "${BASE}/" 50 >/dev/null 2>&1 || true
}

echo "==> limits  gRPC hop-trace = headers/path/metadata only (body modes NONE)."
echo "  Not claimed: protobuf CRS, streaming RPC inspection, or full gRPC WAF."

echo "==> build grpc-echo"
(cd "${GRPC_ECHO_DIR}" && go build -o "${RUN}/grpc-echo" .)

echo "==> start grpc-echo :${GRPC_ORIGIN_PORT}"
: >"${GRPC_HITS}"
stop_pidfile "${RUN}/grpc-echo.pid" TERM
# Clear a leftover listener if a prior run left one without a pidfile.
if [[ -n "$(port_pid "${GRPC_ORIGIN_PORT}")" ]]; then
  kill -KILL "$(port_pid "${GRPC_ORIGIN_PORT}")" 2>/dev/null || true
  sleep 0.2
fi
daemonize "${RUN}/grpc-echo.log" "${RUN}/grpc-echo.pid" \
  "${RUN}/grpc-echo" "127.0.0.1:${GRPC_ORIGIN_PORT}" "${GRPC_HITS}"
ready=0
for _ in $(seq 1 50); do
  if [[ -n "$(port_pid "${GRPC_ORIGIN_PORT}")" ]]; then
    ready=1
    break
  fi
  sleep 0.1
done
[[ "${ready}" -eq 1 ]] \
  && pass "grpc-echo listening" \
  || { fail "grpc-echo not listening"; tail -n 20 "${RUN}/grpc-echo.log" >&2; exit 1; }

echo "==> restart connector with DEMO_CRS=0 + connex-grpc-demo.conf"
build_grpc_rules_no_crs
stop_pidfile "${RUN}/connector.pid" KILL
CONNECTOR_RULES="${RUN}/modsec-grpc.conf" start_connector
wait_http "${METRICS}/healthz" 100 \
  || { echo "grpc-demo connector failed:"; tail -n 40 "${RUN}/connector.log"; exit 1; }

echo "==> restart Envoy with ${GRPC_CFG}"
stop_pidfile "${RUN}/envoy.pid" TERM
daemonize "${RUN}/envoy.log" "${RUN}/envoy.pid" \
  envoy -c "${GRPC_CFG}" --concurrency 2 --log-level warn --file-flush-interval-msec 200
wait_http "http://127.0.0.1:${ENVOY_ADMIN_PORT}/ready" 100 \
  || { echo "grpc Envoy failed:"; tail -n 40 "${RUN}/envoy.log"; restore_stock || true; exit 1; }
trap 'restore_stock || true' EXIT

# --- cells -------------------------------------------------------------------

echo "==> 1. benign Unary (expect OK, origin hit, ModSec allow)"
RID="grpc-allow-$(date -u +%Y%m%dT%H%M%SZ)-$$"
before="$(grpc_hits)"
summary="$(grpc_call "${RID}" -v)"
echo "  client ${summary}"
after="$(grpc_hits)"
if [[ "${summary}" == rc=0* ]] && [[ "${after}" -gt "${before}" ]] \
  && grep -qF "rid=${RID}" "${GRPC_HITS}" \
  && grep -F "request_id=\"${RID}\"" "${RUN}/connector.log" | grep -q 'action="allow"'; then
  pass "[benign] Unary OK, origin + ModSec allow rid=${RID}"
else
  fail "[benign] ${summary} hits ${before}→${after} rid=${RID}"
  grep -F "request_id=\"${RID}\"" "${RUN}/connector.log" | tail -5 || true
  cat "${OUT_DIR}/${RID}.err" | tail -20 || true
fi
line="$(grep -F "rid=${RID} " "${RUN}/envoy.log" | tail -1 || true)"
[[ -n "${line}" ]] && pass "[benign] Envoy access log" || fail "[benign] no Envoy access log"

echo "==> 2. deny metadata header x-demo-grpc-probe: deny (origin untouched)"
RID="grpc-deny-hdr-$(date -u +%Y%m%dT%H%M%SZ)-$$"
before="$(grpc_hits)"
summary="$(grpc_call "${RID}" -v -H 'x-demo-grpc-probe: deny')"
echo "  client ${summary}"
after="$(grpc_hits)"
# Envoy local reply from ModSec is typically HTTP 403; grpcurl non-zero.
if [[ "${summary}" != rc=0* ]] && [[ "${after}" == "${before}" ]] \
  && ! grep -qF "rid=${RID}" "${GRPC_HITS}" 2>/dev/null; then
  pass "[deny-header] blocked, origin untouched (${summary})"
else
  fail "[deny-header] ${summary} hits ${before}→${after}"
fi
if grep -F "request_id=\"${RID}\"" "${RUN}/connector.log" | grep -qE 'action="deny"|fail-closed'; then
  pass "[deny-header] connector deny evidence"
else
  # ImmediateResponse may still log phase complete deny
  if grep -F "request_id=\"${RID}\"" "${RUN}/connector.log" | grep -q 'deny\|403\|modsecurity_intervention'; then
    pass "[deny-header] connector deny evidence (alt)"
  else
    fail "[deny-header] no connector deny log"
    grep -F "request_id=\"${RID}\"" "${RUN}/connector.log" | tail -5 || true
  fi
fi

echo "==> 3. deny SQLi marker in :path (raw HTTP/2 POST, origin untouched)"
RID="grpc-deny-path-$(date -u +%Y%m%dT%H%M%SZ)-$$"
before="$(grpc_hits)"
# Path carries UNION so rule 100102 fires at phase 1 (headers). Not protobuf CRS.
# On HTTP/2 gRPC path, Envoy access log may show 200 + details=modsecurity_intervention
# even when the connector denied with status 403 (ImmediateResponse). Assert deny via
# connector / details, and origin untouched — not curl's http_code alone.
code="$(
  curl -s -o /dev/null -w '%{http_code}' --http2-prior-knowledge --max-time 10 \
    -H "content-type: application/grpc" \
    -H "x-request-id: ${RID}" \
    -X POST --data-binary $'\x00\x00\x00\x00\x00' \
    "http://127.0.0.1:18080/echo.Echo/UnaryUNIONSELECT" || echo 000
)"
sleep 0.4
after="$(grpc_hits)"
line="$(grep -F "rid=${RID} " "${RUN}/envoy.log" | tail -1 || true)"
denied=0
if grep -F "request_id=\"${RID}\"" "${RUN}/connector.log" | grep -q 'action="deny"'; then
  denied=1
fi
if [[ "${line}" == *"modsecurity_intervention"* ]]; then
  denied=1
fi
if [[ "${denied}" -eq 1 ]] && [[ "${after}" == "${before}" ]]; then
  pass "[deny-path] ModSec deny (http_code=${code}, details/action deny), origin untouched"
else
  fail "[deny-path] http=${code} denied=${denied} hits ${before}→${after} line=${line:-none}"
fi

echo "==> 4. fail-closed: connector killed (origin untouched)"
RID="grpc-fc-$(date -u +%Y%m%dT%H%M%SZ)-$$"
before="$(grpc_hits)"
kill -KILL "$(cat "${RUN}/connector.pid")"
sleep 0.3
summary="$(grpc_call "${RID}" -v)"
echo "  client ${summary}"
after="$(grpc_hits)"
# Envoy failure_mode_allow:false → local 500 / Unavailable; never origin.
if [[ "${summary}" != rc=0* ]] && [[ "${after}" == "${before}" ]]; then
  pass "[fail-closed] non-OK, origin untouched (${summary})"
else
  fail "[fail-closed] ${summary} hits ${before}→${after}"
fi
line="$(grep -F "rid=${RID} " "${RUN}/envoy.log" | tail -1 || true)"
if [[ "${line}" == *"ext_proc"* ]] || [[ "${line}" == *"500"* ]]; then
  pass "[fail-closed] Envoy saw ext_proc failure path"
else
  echo "  note: Envoy line=${line:-none}"
  pass "[fail-closed] client non-OK sufficient (Envoy log optional)"
fi
# Restore connector for remaining cells
CONNECTOR_RULES="${RUN}/modsec-grpc.conf" start_connector
wait_http "${METRICS}/healthz" 100 \
  || { fail "[fail-closed] connector restore failed"; exit 1; }
pass "[fail-closed] connector restored"

echo "==> 5. hop-trace.sh --proto grpc (benign + deny header)"
# Inline minimal hop assertions via hop-trace.sh once grpc mode exists.
if "${DEMO}/scripts/hop-trace.sh" --proto grpc --expect-grpc-ok yes --expect-origin yes \
    --grpc-method echo.Echo/Unary; then
  pass "[hop-trace] benign grpc hop-trace OK"
else
  fail "[hop-trace] benign grpc hop-trace FAILED"
fi
if "${DEMO}/scripts/hop-trace.sh" --proto grpc --expect-grpc-ok no --expect-origin no \
    --grpc-method echo.Echo/Unary \
    --grpc-header 'x-demo-grpc-probe: deny'; then
  pass "[hop-trace] deny-header grpc hop-trace OK"
else
  fail "[hop-trace] deny-header grpc hop-trace FAILED"
fi

echo "==> 6. stock CRS on gRPC codec (path SQLi — HTTP-shaped CRS, not protobuf CRS)"
# Reload CRS; keep grpc Envoy + headers-only. Benign Echo/Unary may Continue under
# headers-only (phase-1 alone may not anomaly-block /echo.Echo/Unary). Prove CRS
# still denies when the :path carries a classic SQLi marker — same surface as HTTP.
{
  echo "# Generated by hop-trace-grpc.sh CRS cell — do not edit."
  echo "Include ${DEMO}/rules/engine.conf"
  echo "SecTmpDir ${RUN}/tmp"
  echo "SecDataDir ${RUN}/data"
  echo "SecAuditEngine RelevantOnly"
  echo "SecAuditLogRelevantStatus \"^(?:5|4(?!04))\""
  echo "SecAuditLogParts ABIJDEFHZ"
  echo "SecAuditLogFormat JSON"
  echo "SecAuditLogType Serial"
  echo "SecAuditLog ${RUN}/modsec-audit.log"
  [[ -d "${CRS_DIR}/rules" ]] || "${DEMO}/scripts/install-crs.sh" >&2
  echo "Include ${CRS_DIR}/crs-setup.conf"
  echo "Include ${CRS_DIR}/rules/*.conf"
  echo "Include ${DEMO}/rules/connex-demo.conf"
} >"${RUN}/modsec-grpc-crs.conf"
stop_pidfile "${RUN}/connector.pid" KILL
CONNECTOR_RULES="${RUN}/modsec-grpc-crs.conf" start_connector
wait_http "${METRICS}/healthz" 100 \
  || { fail "[crs] connector with CRS failed"; exit 1; }
RID="grpc-crs-$(date -u +%Y%m%dT%H%M%SZ)-$$"
before="$(grpc_hits)"
code="$(
  curl -s -o /dev/null -w '%{http_code}' --http2-prior-knowledge --max-time 10 \
    -H "content-type: application/grpc" \
    -H "x-request-id: ${RID}" \
    -X POST --data-binary $'\x00\x00\x00\x00\x00' \
    "http://127.0.0.1:18080/search?q=1%27%20UNION%20SELECT%201--" || echo 000
)"
sleep 0.5
after="$(grpc_hits)"
line="$(grep -F "rid=${RID} " "${RUN}/envoy.log" | tail -1 || true)"
denied=0
if grep -F "request_id=\"${RID}\"" "${RUN}/connector.log" | grep -qE 'action="deny"|fail-closed'; then
  denied=1
fi
if [[ "${line}" == *"modsecurity_intervention"* ]]; then
  denied=1
fi
if [[ "${denied}" -eq 1 ]] && [[ "${after}" == "${before}" ]]; then
  pass "[crs] CRS denied SQLi path on gRPC codec (http=${code}; not protobuf CRS)"
else
  fail "[crs] expected deny; http=${code} denied=${denied} hits ${before}→${after}"
  grep -F "request_id=\"${RID}\"" "${RUN}/connector.log" | tail -5 || true
fi

echo
[[ "${PASS}" -ge "${MIN_GRPC_CHECKS}" ]] \
  && pass "[floor] PASS=${PASS} (≥ ${MIN_GRPC_CHECKS})" \
  || fail "[floor] PASS=${PASS} < ${MIN_GRPC_CHECKS}"

echo "transcript: ${TRANSCRIPT}"
if [[ "${FAIL}" -ne 0 ]]; then
  echo "HOP-TRACE-GRPC FAILED (${PASS} passed)"
  exit 1
fi
echo "HOP-TRACE-GRPC PASSED checks=${PASS} (headers/path only — not protobuf CRS)"
