#!/usr/bin/env bash
# Isolated lab for BUFFERED_PARTIAL / NONE / FULL_DUPLEX_STREAMED on alt ports
# (1828x) so it does not collide with the BUFFERED/STREAMED demo on 1808x.
#
# Usage:
#   ./scripts/body-modes-other-lab.sh up BUFFERED_PARTIAL
#   ./scripts/body-modes-other-lab.sh up NONE
#   ./scripts/body-modes-other-lab.sh up FULL_DUPLEX_STREAMED
#   ./scripts/body-modes-other-lab.sh up BUFFERED   # fail-closed control
#   ./scripts/body-modes-other-lab.sh probe
#   ./scripts/body-modes-other-lab.sh fail-closed
#   ./scripts/body-modes-other-lab.sh down
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEMO="${ROOT}/demo"
RUN="${DEMO}/.run-other"
CRS_DIR="${CRS_DIR:-${DEMO}/.crs}"
# Prefer sibling main checkout CRS if worktree has none yet.
if [[ ! -d "${CRS_DIR}/rules" && -d "${ROOT}/../envoy-modsec-connex/demo/.crs/rules" ]]; then
  CRS_DIR="$(cd "${ROOT}/../envoy-modsec-connex/demo/.crs" && pwd)"
fi

BASE_PORT=18280
ENVOY_PORT=$((BASE_PORT + 0))   # 18280
CONNECTOR_PORT=$((BASE_PORT + 1)) # 18281
METRICS_PORT=$((BASE_PORT + 2))   # 18282
ADMIN_PORT=$((BASE_PORT + 9))     # 18289
ORIGIN_PORT=$((BASE_PORT + 18))   # 18298

BASE="http://127.0.0.1:${ENVOY_PORT}"
METRICS="http://127.0.0.1:${METRICS_PORT}"
CONNECTOR_LISTEN="127.0.0.1:${CONNECTOR_PORT}"
CONNECTOR_BIN="${ROOT}/target/debug/ext-proc-modsec"
HITS_FILE="${RUN}/origin-hits.log"
RULES_FILE="${RUN}/modsec.conf"
ENVOY_CFG="${RUN}/envoy.yaml"
MODE_FILE="${RUN}/body_mode"

port_pid() { lsof -tiTCP:"$1" -sTCP:LISTEN 2>/dev/null | head -1 || true; }
http_code() { curl -s -o /dev/null -w '%{http_code}' --max-time 10 "$@" || true; }
origin_hits() { if [[ -f "${HITS_FILE}" ]]; then wc -l <"${HITS_FILE}" | tr -d ' '; else echo 0; fi; }
wait_http() {
  local url="$1" tries="${2:-50}" i
  for ((i = 0; i < tries; i++)); do
    curl -sf -o /dev/null --max-time 2 "$url" && return 0
    sleep 0.2
  done
  return 1
}

daemonize() {
  local log="$1" pidf="$2"
  shift 2
  python3 "${DEMO}/scripts/daemonize.py" "$log" "$pidf" -- "$@"
}

remap_yaml() {
  # remap stock demo YAML ports 1808x → 1828x (+ optional body-mode edits via sed args)
  local src="$1"
  shift
  sed \
    -e "s/port_value: 18089/port_value: ${ADMIN_PORT}/g" \
    -e "s/port_value: 18080/port_value: ${ENVOY_PORT}/g" \
    -e "s/port_value: 18081/port_value: ${CONNECTOR_PORT}/g" \
    -e "s/port_value: 18098/port_value: ${ORIGIN_PORT}/g" \
    "$@" \
    "$src" >"${ENVOY_CFG}"
}

down() {
  for f in envoy.pid connector.pid origin.pid; do
    if [[ -f "${RUN}/$f" ]]; then
      kill -TERM "$(cat "${RUN}/$f")" 2>/dev/null || true
      rm -f "${RUN}/$f"
    fi
  done
  for p in "${ENVOY_PORT}" "${CONNECTOR_PORT}" "${METRICS_PORT}" "${ADMIN_PORT}" "${ORIGIN_PORT}"; do
    local pid
    pid="$(port_pid "$p")"
    [[ -n "$pid" ]] && kill -KILL "$pid" 2>/dev/null || true
  done
  sleep 0.3
}

write_rules() {
  mkdir -p "${RUN}/tmp" "${RUN}/data"
  {
    echo "# Generated by body-modes-other-lab.sh — do not edit."
    echo "Include ${DEMO}/rules/engine.conf"
    echo "SecTmpDir ${RUN}/tmp"
    echo "SecDataDir ${RUN}/data"
    echo "SecAuditEngine RelevantOnly"
    echo "SecAuditLogRelevantStatus \"^(?:5|4(?!04))\""
    echo "SecAuditLogParts ABIJDEFHZ"
    echo "SecAuditLogFormat JSON"
    echo "SecAuditLogType Serial"
    echo "SecAuditLog ${RUN}/modsec-audit.log"
    if [[ "${DEMO_CRS:-1}" == "1" ]]; then
      [[ -d "${CRS_DIR}/rules" ]] || { echo "CRS missing at ${CRS_DIR} — run demo/scripts/install-crs.sh" >&2; exit 2; }
      echo "Include ${CRS_DIR}/crs-setup.conf"
      echo "Include ${CRS_DIR}/rules/*.conf"
    fi
    echo "Include ${DEMO}/rules/connex-demo.conf"
  } >"${RULES_FILE}"
}

up() {
  local mode="${1:?mode}"
  down
  mkdir -p "${RUN}"
  : >"${HITS_FILE}"
  : >"${RUN}/connector.log"
  : >"${RUN}/envoy.log"
  echo "${mode}" >"${MODE_FILE}"
  write_rules

  local body_reply=common
  case "${mode}" in
    BUFFERED)
      remap_yaml "${DEMO}/envoy/envoy.yaml"
      ;;
    BUFFERED_PARTIAL)
      remap_yaml "${DEMO}/envoy/envoy.yaml" \
        -e 's/request_body_mode: BUFFERED/request_body_mode: BUFFERED_PARTIAL/' \
        -e 's/response_body_mode: BUFFERED/response_body_mode: BUFFERED_PARTIAL/'
      # Small listener buffer so oversize prefix drills are practical.
      if ! grep -q 'per_connection_buffer_limit_bytes' "${ENVOY_CFG}"; then
        sed -i.bak 's/name: ingress/name: ingress\n    per_connection_buffer_limit_bytes: 1024/' "${ENVOY_CFG}"
        rm -f "${ENVOY_CFG}.bak"
      fi
      ;;
    NONE)
      remap_yaml "${DEMO}/envoy/envoy.yaml" \
        -e 's/request_body_mode: BUFFERED/request_body_mode: NONE/' \
        -e 's/response_body_mode: BUFFERED/response_body_mode: NONE/'
      ;;
    FULL_DUPLEX_STREAMED)
      body_reply=streamed
      remap_yaml "${DEMO}/envoy/envoy.yaml" \
        -e 's/request_body_mode: BUFFERED/request_body_mode: FULL_DUPLEX_STREAMED/' \
        -e 's/response_body_mode: BUFFERED/response_body_mode: FULL_DUPLEX_STREAMED/' \
        -e 's/request_trailer_mode: SKIP/request_trailer_mode: SEND/' \
        -e 's/response_trailer_mode: SKIP/response_trailer_mode: SEND/'
      ;;
    *)
      echo "unknown mode '${mode}'" >&2
      exit 2
      ;;
  esac

  (cd "${ROOT}" && cargo build -q -p ext-proc-modsec)

  echo "==> origin :${ORIGIN_PORT}"
  daemonize "${RUN}/origin.log" "${RUN}/origin.pid" \
    python3 "${DEMO}/scripts/origin.py" "${ORIGIN_PORT}" "${HITS_FILE}"

  echo "==> connector ${CONNECTOR_LISTEN} body_reply=${body_reply}"
  daemonize "${RUN}/connector.log" "${RUN}/connector.pid" \
    "${CONNECTOR_BIN}" \
    --listen "${CONNECTOR_LISTEN}" \
    --metrics-listen "127.0.0.1:${METRICS_PORT}" \
    --modsec-rules "${RULES_FILE}" \
    --body-reply "${body_reply}"
  if ! wait_http "${METRICS}/healthz" 100; then
    echo "connector failed:" >&2
    tail -n 40 "${RUN}/connector.log" >&2
    exit 1
  fi

  echo "==> envoy :${ENVOY_PORT} mode=${mode}"
  daemonize "${RUN}/envoy.log" "${RUN}/envoy.pid" \
    envoy -c "${ENVOY_CFG}" --concurrency 2 --log-level warn --file-flush-interval-msec 200
  if ! wait_http "http://127.0.0.1:${ADMIN_PORT}/ready" 100; then
    echo "envoy failed:" >&2
    tail -n 60 "${RUN}/envoy.log" >&2
    exit 1
  fi
  echo "Lab up mode=${mode} base=${BASE}"
}

# Shared HTTP probe matrix. Interprets expectations from current mode file.
probe() {
  local mode
  mode="$(tr -d '[:space:]' <"${MODE_FILE}")"
  local fail=0
  expect() {
    local name="$1" want="$2" want_delta="$3"
    shift 3
    local before after code delta
    before="$(origin_hits)"
    code="$(http_code "$@")"
    sleep 0.15
    after="$(origin_hits)"
    delta=$((after - before))
    if [[ "$code" == "$want" && "$delta" == "$want_delta" ]]; then
      echo "  PASS [$name] HTTP $code origin +$delta"
    else
      echo "  FAIL [$name] HTTP $code (want $want) origin +$delta (want +$want_delta)"
      fail=1
    fi
  }

  wait_http "${BASE}/" 50 || { echo "lab not up at ${BASE}" >&2; exit 2; }
  echo "==> probe mode=${mode}"

  case "${mode}" in
    BUFFERED|BUFFERED_PARTIAL|FULL_DUPLEX_STREAMED)
      expect get 200 1 "${BASE}/"
      expect form-sqli 403 0 --data 'a=1%27%20OR%201%3D1--' "${BASE}/"
      expect json-xss 403 0 -H 'Content-Type: application/json' \
        --data '{"q":"<script>alert(1)</script>"}' "${BASE}/"
      expect benign-form 200 1 --data 'hello=world' "${BASE}/"
      expect query-sqli 403 0 "${BASE}/search?q=1%27%20UNION%20SELECT%201--"
      ;;
    NONE)
      # Body attacks must reach origin; query/header CRS can still fire.
      expect get 200 1 "${BASE}/"
      expect form-sqli-bypass 200 1 --data 'a=1%27%20OR%201%3D1--' "${BASE}/"
      expect json-xss-bypass 200 1 -H 'Content-Type: application/json' \
        --data '{"q":"<script>alert(1)</script>"}' "${BASE}/"
      expect query-sqli 403 0 "${BASE}/search?q=1%27%20UNION%20SELECT%201--"
      ;;
  esac

  if [[ "${mode}" == "BUFFERED_PARTIAL" ]]; then
    echo "==> oversize prefix drill (1 KiB listener buffer)"
    # Benign padding (900 bytes) + trailing SQLi past the buffer limit.
    local pad attack
    pad="$(python3 -c 'print("A"*900)')"
    attack="${pad}&a=1%27%20OR%201%3D1--"
    local before after code delta
    before="$(origin_hits)"
    code="$(http_code --data "${attack}" "${BASE}/")"
    sleep 0.2
    after="$(origin_hits)"
    delta=$((after - before))
    echo "  oversize-trailing-sqli → HTTP ${code} origin +${delta}"
    # Honest outcome: prefix-only may miss trailing attack (200) or still deny (403).
    # Record both; do not claim CRS completeness.
    echo "  NOTE: PREFIX honesty — trailing attack after limit is not a CRS claim"
  fi

  [[ "$fail" -eq 0 ]] || exit 1
  echo "probe PASS mode=${mode}"
}

fail_closed_quick() {
  # Minimal fail-closed: kill connector → expect 500 on next request; restart not done here.
  local mode
  mode="$(tr -d '[:space:]' <"${MODE_FILE}")"
  wait_http "${BASE}/" 20 || { echo "lab not up" >&2; exit 2; }
  echo "==> fail-closed quick (kill connector) mode=${mode}"
  local cpid
  cpid="$(cat "${RUN}/connector.pid")"
  kill -KILL "$cpid" 2>/dev/null || true
  rm -f "${RUN}/connector.pid"
  sleep 0.3
  local code
  code="$(http_code "${BASE}/")"
  if [[ "$code" == "500" || "$code" == "503" ]]; then
    echo "  PASS kill-connector → HTTP ${code}"
  else
    echo "  FAIL kill-connector → HTTP ${code} (want 500/503)"
    exit 1
  fi
}

cmd="${1:-}"
case "${cmd}" in
  up) shift; up "$@" ;;
  down) down ;;
  probe) probe ;;
  fail-closed) fail_closed_quick ;;
  *)
    echo "usage: $0 {up MODE|down|probe|fail-closed}" >&2
    exit 2
    ;;
esac
